const ring = (n: number, r: number, fn: (x: number, y: number, a: number, i: number) => Item, cx = 200, cy = 200): Item[] =>
  Array.from({ length: n }, (_, i) => {
    const a = (i / n) * Math.PI * 2 - Math.PI / 2
    return fn(cx + r * Math.cos(a), cy + r * Math.sin(a), a, i)
  })

